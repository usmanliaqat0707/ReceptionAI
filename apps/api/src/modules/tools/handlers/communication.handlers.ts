import {
  ToolDefinition,
  ToolExecutionContext,
  NormalizedToolResult,
} from "../tool-registry";
import {
  sendSmsToolSchema,
  SendSmsToolInput,
  sendEmailToolSchema,
  SendEmailToolInput,
} from "@receptionai/validation";
import { CommunicationDeliveryService } from "../../communications/services/communication-delivery.service";

export const sendSmsTool: ToolDefinition<SendSmsToolInput> = {
  name: "send_sms",
  description:
    "Send a policy-controlled transactional SMS notification (e.g. appointment confirmation, callback confirmation, message receipt) to a known contact. Recipient and body are securely generated by the server from approved templates.",
  capability: "SEND_COMMUNICATIONS",
  sideEffect: "WRITE",
  requiresIdempotency: true,
  requiresConfirmation: false,
  inputSchema: sendSmsToolSchema,
  async execute(
    context: ToolExecutionContext,
    input: SendSmsToolInput
  ): Promise<NormalizedToolResult> {
    // 1. Anti-Open-Relay Guard: Check raw forbidden properties if caller tries to bypass
    const rawInput = input as any;
    if (rawInput.to || rawInput.phone || rawInput.body || rawInput.text || rawInput.message) {
      return {
        success: false,
        error: {
          code: "SECURITY_POLICY_VIOLATION",
          message:
            "Arbitrary recipient phone numbers or message bodies are strictly prohibited. You must supply contactId and purpose only.",
        },
      };
    }

    try {
      const comm = await CommunicationDeliveryService.enqueue({
        workspaceId: context.workspaceId,
        channel: "SMS",
        purpose: input.purpose,
        contactId: input.contactId,
        sourceId: input.relatedResourceId,
        receptionistId: context.receptionistId,
        testSessionId: context.testSessionId,
        idempotencyKey: `tool-sms:${context.testSessionId || context.workspaceId}:${input.contactId}:${input.purpose}:${input.relatedResourceId || "none"}`,
      });

      if (!comm) {
        return {
          success: false,
          error: {
            code: "COMMUNICATION_SUPPRESSED_OR_DISABLED",
            message: "SMS communication was suppressed or is disabled by workspace policy.",
          },
        };
      }

      if (process.env.NODE_ENV === "test") {
        await CommunicationDeliveryService.processOutbox(context.workspaceId).catch(() => {});
      }

      return {
        success: true,
        data: {
          communicationId: comm.id,
          status: comm.status,
          message: "SMS notification queued for delivery.",
        },
      };
    } catch (err: any) {
      return {
        success: false,
        error: {
          code: "SMS_SEND_FAILED",
          message: err.message || "Failed to enqueue SMS notification.",
        },
      };
    }
  },
};

